#!/usr/bin/env python3
"""
V1 static audits of the decompilation (PLAN 4b V1, LOG 2026-10-07 STEP 1).

    tools/mgst_audit.py [--facts DIR] [--report FILE]

Each audit checks what the recompile pipeline actually consumes against an
INDEPENDENT source of truth. Exit status 1 if any check fails, so it can gate
CI (V7) and catch type-pipeline regressions like the 2026-09-30 C++ layout
wipe (ApplyObjcTypes re-run after ApplyCppTypes).

A1 layouts    recovered/compile/mgst_types.fixed.h (the header every
              recompiled function includes), compiled with the recompile ABI
              (tools/mgst_recompile.py CFLAGS), against:
              - every ObjC ivar's offset and size and every class's
                instance size from the binary's runtime metadata
                (analysis/objc/ivars.tsv, classes.tsv), inherited ivars
                included;
              - every C++ `new T` allocation size in the corpus
                (sizeof(T) must equal it).
A2 returns    for every objc_msgSend* call whose result is used, the return
              type the decompiler applied (DumpV1Facts.java) against the
              method's type encoding (methods.tsv / external_methods.tsv),
              via the static selector or, when the selector is shared by
              methods of different return types, the receiver classes seen at
              runtime (analysis/dynamic/msgsend_sites.tsv).
A3 switches   every Apple switch-helper call site, its inline table decoded
              here from MGSTUS bytes, against the decompiler's jump tables
              (destinations and case labels) and the runtime-seen targets.
A4 imports    every import stub called by MGSTUS has a non-default prototype.

Facts: analysis/verification/v1/ (tools/ghidra/DumpV1Facts.java).
"""
import argparse
import collections
import json
import os
import re
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
CDIR = os.environ.get("MGST_CDIR") or os.path.join(ROOT, "recovered/compile")   # MGST_CDIR: audit another export (rebuild check)
OBJC = os.path.join(ROOT, "analysis/objc")
REF_EXE = os.path.join(ROOT, "work/extracted/Payload/MGSTUS.app/MGSTUS")
SW = {0x5a5b4: "___switchu8", 0x5a5cc: "___switch8", 0x5a5e4: "___switch16"}


def tsv(path):
    rows = []
    hdr = None
    for l in open(path):
        if l.startswith("#") or not l.strip():
            continue
        p = l.rstrip("\n").split("\t")
        if hdr is None:
            hdr = p
            continue
        rows.append(dict(zip(hdr, p)))
    return rows


class Report:
    def __init__(self):
        self.sections = []
        self.failed = 0

    def section(self, title, summary, failures, notes=()):
        self.failed += len(failures)
        self.sections.append((title, summary, failures, list(notes)))
        print("%-12s %s%s" % (title, "PASS " if not failures else "FAIL ", summary))
        for f in failures[:15]:
            print("    " + f)
        if len(failures) > 15:
            print("    ... %d more" % (len(failures) - 15))

    def write(self, path):
        o = ["# V1 static audit report", "",
             "Generated by `tools/mgst_audit.py` (PLAN 4b V1). Each audit checks what the",
             "recompile pipeline consumes against an independent source. **%s**" % (
                 "All audits pass." if not self.failed else "%d failing check(s)." % self.failed), ""]
        o.append("| audit | result | summary |")
        o.append("|---|---|---|")
        for t, s, f, _ in self.sections:
            o.append("| %s | %s | %s |" % (t, "PASS" if not f else "**FAIL (%d)**" % len(f), s))
        for t, s, f, n in self.sections:
            o += ["", "## " + t, "", s, ""]
            for x in n:
                o.append("- " + x)
            if f:
                o += ["", "Failures:", "", "```"] + f + ["```"]
        open(path, "w").write("\n".join(o) + "\n")


# ---------------------------------------------------------------- A1 layouts
CANARY = "canary (must fail)"

def audit_layouts(rep):
    import mgst_recompile
    classes = {r["class"]: r for r in tsv(os.path.join(OBJC, "classes.tsv"))}
    ivars = collections.defaultdict(list)
    for r in tsv(os.path.join(OBJC, "ivars.tsv")):
        ivars[r["class"]].append(r)
    hdr = open(os.path.join(CDIR, "mgst_types.fixed.h")).read()
    have = set(re.findall(r"^struct (\w+) \{", hdr, re.M))

    def chain(c):
        out = []
        while c in classes and c not in out:
            out.append(c)
            c = classes[c]["super"]
        return out
    checks = []          # (C condition, description)
    nostruct = []
    for c in sorted(classes):
        if c not in have:
            if ivars.get(c):
                nostruct.append(c)
            continue
        for k in chain(c):
            for iv in ivars.get(k, []):
                f = iv["name"]
                checks.append(("__builtin_offsetof(struct %s, %s) == %s" % (c, f, iv["offset"]),
                               "%s.%s (declared in %s) offset %s" % (c, f, k, iv["offset"])))
                checks.append(("sizeof(((struct %s *)0)->%s) == %s" % (c, f, iv["size"]),
                               "%s.%s size %s" % (c, f, iv["size"])))
        isz = int(classes[c]["instance_size"])
        checks.append(("sizeof(struct %s) == ((%d + __alignof__(struct %s) - 1) & ~(__alignof__(struct %s) - 1))"
                       % (c, isz, c, c), "%s instance size %d (runtime class_ro_t)" % (c, isz)))
    # C++: `(T *)operator_new(N)` followed by T's constructor or init in the corpus
    news = {}
    for fn in os.listdir(os.path.join(ROOT, "recovered/decompiled")):
        for m in re.finditer(r"\((\w+) \*\)operator_new\((0x[0-9a-f]+|\d+)\)",
                             open(os.path.join(ROOT, "recovered/decompiled", fn)).read()):
            news.setdefault(m.group(1), set()).add(int(m.group(2), 0))
    for t, sizes in sorted(news.items()):
        if t not in have:
            nostruct.append(t + " (C++)")
            continue
        for n in sorted(sizes):
            checks.append(("sizeof(struct %s) == %d" % (t, n), "C++ %s: sizeof == new size 0x%x" % (t, n)))
    checks.append(("sizeof(struct EneDat) == 0x2fc", "EneDat record stride 0x2fc (enemy_data indexing)"))
    checks.append(("sizeof(struct EneDat) == 0x2fd", CANARY))
    src = ['#include "mgst_types.fixed.h"']
    first = len(src) + 1
    for cond, _ in checks:
        src.append("_Static_assert(%s, \"\");" % cond)
    with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as t:
        t.write("\n".join(src) + "\n")
    r = subprocess.run(["clang"] + mgst_recompile.CFLAGS + ["-ferror-limit=0", "-fsyntax-only", "-I", CDIR, t.name],
                       capture_output=True, text=True)
    os.unlink(t.name)
    bad = {}
    for m in re.finditer(r"^%s:(\d+):\d+: error: (.*)$" % re.escape(t.name), r.stderr, re.M):
        bad.setdefault(int(m.group(1)), m.group(2))
    fails = []
    canary = False
    for ln, err in sorted(bad.items()):
        k = ln - first
        if 0 <= k < len(checks) and checks[k][1] == CANARY:
            canary = True
        elif 0 <= k < len(checks):
            fails.append("%s  [%s]" % (checks[k][1], err[:90]))
        else:
            fails.append("header line %d: %s" % (ln, err[:120]))
    if not canary:
        fails.append("CANARY: the deliberately false assertion was NOT reported - the audit is blind")
    checks.pop()
    notes = ["%d checks: ivar offsets+sizes (with inherited ivars) for %d ObjC class structs, "
             "instance sizes, %d C++ allocation sizes, EneDat stride" % (
                 len(checks), len([c for c in classes if c in have]), sum(len(v) for v in news.values()))]
    if nostruct:
        notes.append("no struct in the compile header (not checked): " + ", ".join(nostruct))
    rep.section("A1 layouts", "%d layout checks against runtime metadata and allocation sizes" % len(checks),
                fails, notes)


# ---------------------------------------------------------------- A2 returns
def ret_objc(enc):
    """Return class from an ObjC method type encoding (methods.tsv), e.g.
    `f8@0:4` = float return, 8-byte frame (the digits are frame offsets)."""
    e = enc.lstrip("rnNoORV")
    if not e:
        return None
    return {"f": "float", "d": "double", "q": "int64", "Q": "int64", "v": "void",
            "{": "struct"}.get(e[0], "int")


def ret_ext(t):
    """Return class from external_methods.tsv notation (f4 float, f8 double)."""
    if t == "f4":
        return "float"
    if t == "f8":
        return "double"
    if t in ("i8", "u8"):
        return "int64"
    if t == "void":
        return "void"
    if t.startswith("struct"):
        return "struct"
    return "int"


def audit_returns(rep, facts):
    sel_ret = collections.defaultdict(set)
    meth = {}
    for r in tsv(os.path.join(OBJC, "methods.tsv")):
        rc = ret_objc(r["types"])
        sel_ret[r["selector"]].add(rc)
        meth[(r["class"], r["kind"], r["selector"])] = rc
    ext = {}
    for l in open(os.path.join(OBJC, "external_methods.tsv")):
        if l.startswith("#") or not l.strip():
            continue
        p = l.rstrip("\n").split("\t")
        ext[p[0]] = ret_ext(p[1])
        sel_ret[p[0]].add(ext[p[0]])
    sup = {r["class"]: r["super"] for r in tsv(os.path.join(OBJC, "classes.tsv"))}

    def lookup(cls, kind, sel):
        c = cls
        while c and c != "?":
            if (c, kind, sel) in meth:
                return meth[(c, kind, sel)]
            c = sup.get(c)
        return ext.get(sel)
    runtime = {}
    for r in tsv(os.path.join(ROOT, "analysis/dynamic/msgsend_sites.tsv")):
        runtime[int(r["site"], 16)] = re.findall(r"([+-])\[(\S+) ([^\]]+)\]", r["observed"])
    fails, undetermined = [], []
    n_used = n_checked = 0
    via = collections.Counter()
    for r in tsv(os.path.join(facts, "v1_msgsend.tsv")):
        if r["out_size"] == "0":
            continue
        n_used += 1
        site = int(r["site"], 16)
        sels = [] if r["selectors"] == "?" else r["selectors"].split("|")
        # the receiver classes seen at runtime are the strongest evidence (a
        # selector can look unique only because the SDK class is not in
        # methods.tsv, e.g. -[UIAcceleration z]); else the static selector
        obs = runtime.get(site, [])
        if obs:
            exp = {lookup(c, k, s) for k, c, s in obs}
            via["runtime receiver"] += 1
            if None in exp:
                # a real receiver class with no signature in either table: the
                # call-site typing had to guess (e.g. -[UIAcceleration z])
                miss = sorted("%s[%s %s]" % (k, c, s) for k, c, s in obs if lookup(c, k, s) is None)
                fails.append("%s %s: no signature for runtime receiver %s; decompiler used %s (%s bytes)" % (
                    r["site"], r["function"], ", ".join(miss), r["out_type"], r["out_size"]))
                continue
        else:
            exp = set()
            for s in sels:
                exp |= sel_ret.get(s, {None})
            if len(exp) != 1 or None in exp:
                undetermined.append("%s %s sel=%s" % (r["site"], r["function"], r["selectors"]))
                continue
            via["selector"] += 1
        if len(exp) != 1 or None in exp:
            undetermined.append("%s %s sel=%s expected=%s" % (r["site"], r["function"], r["selectors"], exp))
            continue
        e = exp.pop()
        n_checked += 1
        ty, sz = r["out_type"], int(r["out_size"])
        isfloat = "*" not in ty and ty.startswith(("float", "double"))
        ok = {"float": ty == "float" and sz == 4,
              "double": ty == "double" and sz == 8,
              "int64": sz == 8 and not isfloat,
              "int": sz <= 4 and not isfloat,
              "struct": True,
              "void": False}[e]
        if not ok:
            fails.append("%s %s [%s] expects %s, decompiler used %s (%d bytes)" % (
                r["site"], r["function"], r["selectors"], e, ty, sz))
    notes = ["%d call results used; %d checked (%s); %d undetermined (selector unknown or shared by "
             "methods with different return types and never observed at runtime)" % (
                 n_used, n_checked, ", ".join("%d via %s" % (v, k) for k, v in via.items()), len(undetermined))]
    notes += ["undetermined: " + u for u in undetermined]
    rep.section("A2 returns", "msgSend result types vs method encodings: %d checked, %d undetermined" % (
        n_checked, len(undetermined)), fails, notes)


# ---------------------------------------------------------------- A3 switches
def audit_switches(rep, facts):
    import macho
    data = open(REF_EXE, "rb").read()
    segs = macho.parse(data) if hasattr(macho, "parse") else None

    def va2off(va):
        for s in SEGS:
            if s[0] <= va < s[0] + s[1]:
                return s[2] + va - s[0]
        raise ValueError(hex(va))
    global SEGS
    SEGS = []
    # LC_SEGMENT (0x1): vmaddr, vmsize, fileoff
    ncmds = struct.unpack_from("<I", data, 16)[0]
    off = 28
    text = None
    for _ in range(ncmds):
        cmd, size = struct.unpack_from("<II", data, off)
        if cmd == 1:
            name = data[off + 8:off + 24].rstrip(b"\0").decode()
            vmaddr, vmsize, fileoff, filesize = struct.unpack_from("<IIII", data, off + 24)
            SEGS.append((vmaddr, filesize, fileoff))
            nsect = struct.unpack_from("<I", data, off + 48)[0]
            for k in range(nsect):
                so = off + 56 + 68 * k
                sn = data[so:so + 16].rstrip(b"\0").decode()
                if name == "__TEXT" and sn == "__text":
                    a, sz = struct.unpack_from("<II", data, so + 32)
                    text = (a, sz)
        off += size
    # scan __text for Thumb BL/BLX to the helpers
    sites = {}
    a0, sz = text
    base = va2off(a0)
    for i in range(0, sz - 4, 2):
        h0, h1 = struct.unpack_from("<HH", data, base + i)
        if (h0 & 0xf800) != 0xf000 or (h1 & 0xf800) not in (0xf800, 0xe800):
            continue
        pc = a0 + i
        o = ((h0 & 0x7ff) << 12) | ((h1 & 0x7ff) << 1)
        if o & 0x400000:
            o -= 0x800000
        t = pc + 4 + o
        if (h1 & 0xf800) == 0xe800:
            t &= ~3
        if t in SW:
            sites[pc] = SW[t]
    jt = collections.defaultdict(list)
    for r in tsv(os.path.join(facts, "v1_jumptables.tsv")):
        jt[r["entry"]].append((int(r["switch"], 16), r["label"], int(r["dest"], 16)))
    # map each site to its function (entries sorted)
    entries = sorted(int(l, 16) for l in open(os.path.join(ROOT, "analysis/symbols/function_entries.txt")))
    import bisect
    runtime = {int(r["site"], 16): r for r in tsv(os.path.join(ROOT, "analysis/dynamic/switch_targets.tsv"))
               if re.match(r"^0x[0-9a-f]+$", r["site"])}
    fails, notes = [], []
    used_tables = set()
    label_kind = collections.Counter()
    n_ok = 0
    for pc, helper in sorted(sites.items()):
        ret = pc + 4
        ro = va2off(ret)
        if helper == "___switch16":
            cnt = struct.unpack_from("<H", data, ro)[0]
            ent = list(struct.unpack_from("<%dh" % (cnt + 1), data, ro + 2))
        else:
            cnt = data[ro]
            ent = list(struct.unpack_from("<%d%s" % (cnt + 1, "B" if helper == "___switchu8" else "b"), data, ro + 1))
        exp = {ret + 2 * e for e in ent}
        fe = entries[bisect.bisect_right(entries, pc) - 1]
        tables = [x for x in jt.get("%08x" % fe, []) if abs(x[0] - pc) <= 8]
        if not tables:
            fails.append("0x%x %s in fn 0x%x: no decompiler jump table at this site" % (pc, helper, fe))
            continue
        used_tables.add((fe, tables[0][0]))
        got = {d for _, _, d in tables}
        if got != exp:
            fails.append("0x%x %s: decompiler targets %s != table targets %s" % (
                pc, helper, sorted(map(hex, got - exp)), sorted(map(hex, exp - got))))
            continue
        labs = [(int(l), d) for _, l, d in tables if l != "?"]
        by_value = all(ret + l == d for l, d in labs)
        by_index = all(0 <= l <= cnt and ret + 2 * ent[l] == d for l, d in labs)
        # the compiler's `idx = n - k` before the call, folded by the decompiler
        # into the labels (case n): accept a bias only if it IS the immediate
        # of a Thumb SUBS (imm3 0x1e00 / imm8 0x3800) in the 4 insns before
        subs = set()
        for back in range(1, 5):
            h = struct.unpack_from("<H", data, va2off(pc - 2 * back))[0]
            if h & 0xfe00 == 0x1e00:
                subs.add((h >> 6) & 7)
            elif h & 0xf800 == 0x3800:
                subs.add(h & 0xff)
        by_bias = next((b for b in sorted(subs) if all(0 <= l - b <= cnt and ret + 2 * ent[l - b] == d
                                                        for l, d in labs)), None)
        if by_bias is not None and not (by_value or by_index):
            label_kind["index+%d (folded subs)" % by_bias] += 1
        elif not (by_value or by_index):
            fails.append("0x%x %s: case labels map to wrong targets (neither entry*2 nor index): %s" % (
                pc, helper, [(l, hex(d)) for l, d in labs][:4]))
            continue
        else:
            label_kind[("value" if by_value else "index")] += 1
        rt = runtime.get(pc)
        if rt and rt["seen_targets"]:
            seen = {int(x, 16) for x in rt["seen_targets"].split()}
            if not seen <= exp:
                fails.append("0x%x: runtime targets outside the table: %s" % (pc, sorted(map(hex, seen - exp))))
                continue
        n_ok += 1
    other = sorted({(int(e, 16), sw) for e, rows in jt.items() for sw, _, _ in rows} - used_tables)
    if other:
        notes.append("decompiler jump tables not at a switch-helper site (ordinary compiled switches): %d" % len(other))
    notes.append("case labels: %s (both exact: every label maps to its table target)" % dict(label_kind))
    notes.append("%d helper call sites found by scanning __text; %d with runtime observations (all checked "
                 "for containment)" % (len(sites), len([p for p in sites if p in runtime])))
    rep.section("A3 switches", "%d/%d switch-helper sites: decompiler targets == inline table, every case label maps to its table target" % (
        n_ok, len(sites)), fails, notes)


# ---------------------------------------------------------------- A4 imports
def audit_imports(rep):
    stubs = {r["symbol"]: int(r["addr"], 16) for r in tsv(os.path.join(ROOT, "analysis/symbols/stubs_v230.tsv"))}
    protos = {}
    for l in open(os.path.join(CDIR, "functions.jsonl")):
        f = json.loads(l)
        if f.get("c") is None:
            protos[f["name"]] = f["proto"]
    softfloat = re.compile(r"^___\w+vfp$|^___(div|mod|udiv|umod)si3$|^___switch")
    objc = re.compile(r"^_objc_msgSend")
    fails, notes = [], []
    n = 0
    for s in sorted(stubs):
        if softfloat.match(s):
            notes.append("%s: soft-float/switch helper, modelled as a p-code callfixup" % s)
            continue
        p = protos.get(CXX.get(s, s))
        n += 1
        if p is None:
            fails.append("%s: no prototype exported" % s)
        elif re.search(r"\bundefined\d*\b", p):
            fails.append("%s: default/undefined prototype: %s" % (s, p))
    rep.section("A4 imports", "%d import stubs prototyped (excluding %d helpers modelled as callfixups)" % (
        n, len(notes)), fails, notes)


# C++ runtime stubs are exported under their demangled Ghidra names
CXX = {"__Znwm": "<EXTERNAL>::operator_new", "__Znam": "<EXTERNAL>::operator_new",
       "__ZdlPv": "<EXTERNAL>::operator_delete", "__ZdaPv": "<EXTERNAL>::operator_delete"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--facts", default=os.path.join(ROOT, "analysis/verification/v1"))
    ap.add_argument("--report", default=os.path.join(ROOT, "analysis/verification/v1_audit.md"))
    a = ap.parse_args()
    rep = Report()
    audit_layouts(rep)
    audit_returns(rep, a.facts)
    audit_switches(rep, a.facts)
    audit_imports(rep)
    rep.write(a.report)
    print("report: %s  (%s)" % (os.path.relpath(a.report, ROOT),
                                "PASS" if not rep.failed else "%d failing" % rep.failed))
    sys.exit(1 if rep.failed else 0)


if __name__ == "__main__":
    main()
