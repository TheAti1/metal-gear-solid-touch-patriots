/* Export everything needed to RECOMPILE the decompiled functions one by one
 * and link them against the original binary (step 7' differential testing).
 *
 *   <out>/mgst_types.gen.h   every data type in the project (DataTypeWriter)
 *   <out>/functions.jsonl    per function: addr, thumb, name, cname, proto, c
 *   <out>/symbols.tsv        name, cname, addr, kind (func_thumb|func_arm|data),
 *                            C type of defined data
 *
 * cname = C-safe identifier (`::` -> `__`, other non-identifier chars -> `_`);
 * tools/mgst_recompile.py applies the same rule to the decompiled text.
 * Functions whose cname collides (C++ overloads, C1/C2 constructors) get a
 * unique cname `<cname>__<hexaddr>`; symbols.tsv lists both.
 *
 * C text (LOG 2026-10-07 STEP 2): printed from the decompiler's token tree,
 * not getC(), so facts the plain text loses are kept. Each token links to
 * its p-code op:
 *   - calls name their exact target (unique cname): overloads and C1/C2
 *     constructors no longer collapse into one C name;
 *   - every objc_msgSend* call is preceded by a site marker comment
 *     `/ *@0xSITE* /` and functions.jsonl carries that site's override
 *     prototype (ApplyCallsiteSignatures) under "sites";
 *   - `(T)x` whose op is CAST (same size, float <-> int/pointer) becomes
 *     __BITCAST(T, x): Ghidra prints a bit reinterpretation and an INT2FLOAT
 *     conversion identically;
 *   - a load/store through `void *` gets its width: *(undefinedN *)p;
 *   - globals print as their cname (function statics `f(args)::x`, CFString
 *     names); a param/local named like a global it shadows gets suffix `_l`
 *     (Ghidra prints the global as `::name`);
 * and "globals" records the type the decompiler gave each global's variable
 * (the propagated type, e.g. Sound *, not the undefined4 storage).
 * Self-check: the same printer without transformations must reproduce
 * getC() exactly; mismatches are counted in the log.
 *
 * Usage: analyzeHeadless ... -postScript ExportCompilable.java <outdir>
 */
