#!/usr/bin/env python3
"""Per-function TEST coverage (LOG 2026-10-10): which share of each function's
own instructions did passing differential tests actually execute in the
original code?

A pass proves identical behaviour on the paths the test ran. This measures
those paths: for every result row of the CURRENT build (fingerprint) with
verdict pass and a `cov` field (recorded by tools/mgst_difftest.py since
2026-10-10), the covered instruction offsets are united per function and
compared with the function's instructions as the decompiler sees them
(recovered/compile/function_insns.tsv, tools/ghidra/CoverageAudit.java).

  tools/mgst_testcov.py
Outputs analysis/verification/test_coverage.{tsv,md}.
"""
import collections
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CDIR = os.path.join(ROOT, "recovered/compile")
OUT = os.path.join(ROOT, "analysis/verification")


def cov_decode(s, base):
    out = set()
    for part in s.split(","):
        if not part:
            continue
        a, _, b = part.partition("-")
        lo = int(a, 16)
        hi = int(b, 16) if b else lo
        out.add((base + lo, base + hi))
    return out


def main():
    insns = collections.defaultdict(list)
    for l in open(os.path.join(CDIR, "function_insns.tsv")):
        p = l.rstrip("\n").split("\t")
        if p[0] != "function":
            insns[int(p[0], 16)].append(int(p[1], 16))
    names, status = {}, {}
    for l in open(os.path.join(OUT, "function_status.tsv")):
        p = l.rstrip("\n").split("\t")
        if p[0].startswith("0x"):
            names[int(p[0], 16)] = p[1]
            status[int(p[0], 16)] = (p[4], p[5] if len(p) > 5 else "")
    cur = {}
    for f in glob.glob(os.path.join(CDIR, "fn", "*.fp")):
        cur[int(os.path.basename(f)[:-3], 16)] = open(f).read().strip()
    ranges = collections.defaultdict(set)
    rows_with_cov = collections.Counter()
    for pat in ("difftest_offline*.jsonl", "difftest_frames*.jsonl", "difftest_calls*.jsonl"):
        for path in glob.glob(os.path.join(CDIR, pat)):
            for l in open(path):
                if '"cov"' not in l:
                    continue
                r = json.loads(l)
                a = int(r["addr"], 16)
                if r.get("verdict") != "pass" or r.get("fp") != cur.get(a):
                    continue
                ranges[a] |= cov_decode(r["cov"], a)
                rows_with_cov[a] += 1
    rows = []
    tot_i = tot_c = 0
    for a in sorted(insns):
        ins = sorted(insns[a])
        rs = sorted(ranges.get(a, ()))
        cov = {x for x in ins if any(lo <= x <= hi for lo, hi in rs)} if rs else set()
        verdict, v0 = status.get(a, ("?", ""))
        if verdict == "pass":
            tot_i += len(ins)
            tot_c += len(cov)
        # uncovered instruction runs (for targeting new states)
        unc, run = [], None
        for x in ins:
            if x in cov:
                if run:
                    unc.append(run)
                    run = None
            else:
                run = [x, x] if not run else [run[0], x]
        if run:
            unc.append(run)
        rows.append((a, names.get(a, "?"), verdict, "V0" if v0 else "", len(ins), len(cov), rows_with_cov[a],
                     " ".join("%x-%x" % (lo, hi) if lo != hi else "%x" % lo for lo, hi in unc[:12])))
    with open(os.path.join(OUT, "test_coverage.tsv"), "w") as w:
        w.write("addr\tfunction\tverdict\tv0\tinstructions\tcovered\tpct\trows_with_cov\tuncovered_runs(first 12)\n")
        for a, n, v, v0, ni, nc, rc, unc in rows:
            w.write("0x%x\t%s\t%s\t%s\t%d\t%d\t%.1f\t%d\t%s\n" % (a, n, v, v0, ni, nc, 100.0 * nc / max(1, ni), rc, unc))
    proven = [r for r in rows if r[2] == "pass"]
    measured = [r for r in proven if r[6] > 0]
    buckets = collections.Counter()
    for r in measured:
        p = 100.0 * r[5] / max(1, r[4])
        buckets["100 %" if p >= 99.999 else ">= 90 %" if p >= 90 else ">= 75 %" if p >= 75 else
                ">= 50 %" if p >= 50 else ">= 25 %" if p >= 25 else "< 25 %"] += 1
    with open(os.path.join(OUT, "test_coverage.md"), "w") as w:
        w.write("# Test coverage: which code did the passing tests execute?\n\n")
        w.write("Generated by `tools/mgst_testcov.py`. For every proven function, the share of its own\n"
                "instructions (as the decompiler sees them) that passing differential tests executed in\n"
                "the original code. A proof holds for the paths it ran; uncovered paths are decompiled and\n"
                "compile, but no test exercised them.\n\n")
        w.write("| | |\n|---|---:|\n")
        w.write("| proven functions | %d |\n" % len(proven))
        w.write("| with coverage data (tested since coverage recording) | %d |\n" % len(measured))
        w.write("| **instructions of proven functions executed by passing tests** | **%d / %d (%.1f %%)** |\n" % (
            tot_c, tot_i, 100.0 * tot_c / max(1, tot_i)))
        w.write("\n| functions by coverage | count |\n|---|---:|\n")
        for k in ("100 %", ">= 90 %", ">= 75 %", ">= 50 %", ">= 25 %", "< 25 %"):
            w.write("| %s | %d |\n" % (k, buckets[k]))
        w.write("\nPer function (with the first uncovered instruction runs): `test_coverage.tsv`.\n")
    print("test coverage: %d/%d instructions of proven functions (%.1f %%); %d of %d proven functions measured; %s" % (
        tot_c, tot_i, 100.0 * tot_c / max(1, tot_i), len(measured), len(proven), dict(buckets)))


if __name__ == "__main__":
    main()
