STACK_VAR = re.compile(r"^([ \t]+)(?![ \t])(?!(?:return|goto|case|break|continue|else|do)\b)([^;\n()=]*?)\s*\b((?:local_|[A-Za-z]*Stack_)([0-9a-f]+))\s*(\[(\d+)\])?;[ \t]*$", re.M)


def stack_frame_overlay(src):
    """Ghidra splits a stack array into scalar locals named by their entry-SP
    offset (local_70, local_6c, ... / auStack_64 [4]) and passes &local_70 as
    the array (glVertexPointer(3, GL_FLOAT, 0, &local_70)). Compiled as
    separate variables they are NOT contiguous. When any stack-named local has
    its address taken, every stack-named local becomes a view into one frame
    buffer at its original offset: layout (and overlap) exactly as in the
    original frame. Returns (src, number of locals overlaid)."""
    ob = src.find("{\n")
    if ob < 0:
        return src, 0
    eb = src.find("\n\n", ob)            # end of the declaration block
    if eb < 0:
        return src, 0
    decls = list(STACK_VAR.finditer(src, ob, eb + 1))
    if not decls:
        return src, 0
    names = {m.group(3) for m in decls}
    body = src[decls[-1].end():]
    if not any(re.search(r"&\s*%s\b" % re.escape(n), body) for n in names) and \
       not any(m.group(5) for m in decls):
        return src, 0
    top = max(int(m.group(4), 16) for m in decls)
    top = (top + 7) & ~7
    out, last = [], 0
    for i, m in enumerate(decls):
        ind, ctype, name, off = m.group(1), m.group(2).strip(), m.group(3), int(m.group(4), 16)
        pos = top - off
        if m.group(5):
            repl = "%s#define %s ((%s *)(__frame + %d))" % (ind, name, ctype, pos)
        else:
            repl = "%s#define %s (*(%s *)(__frame + %d))" % (ind, name, ctype, pos)
        if i == 0:
            repl = "%sunsigned char __frame[%d] __attribute__((aligned(8)));\n" % (ind, top) + repl
        out.append(src[last:m.start()] + repl.replace("%s#define" % ind, "#define"))
        last = m.end()
    out.append(src[last:])
    return "".join(out), len(decls)


# --- float semantics: clang's soft-float libcalls as real VFP instructions
# ARMv6 Thumb-1 has no VFP instructions, so clang compiles float maths to
# libgcc soft-float calls (__mulsf3, __lesf2, ...). libgcc emulates IEEE in
# integer code and ignores the FPSCR: no flush-to-zero, no default NaN. The
# original calls Apple's ___*vfp helpers, each one ARM-mode VFP instruction
# under the device FPSCR (FZ+DN). The shims below are those same
# instructions: C compiled in ARM mode with VFPv2 (a*b -> vmul.f32, a<=b ->
# vcmpe.f32 + vmrs), exporting the libgcc names and the libgcc result
# conventions (__lesf2(a,b) <= 0 iff a <= b, unordered -> the "false" side).
# They do not go through MGSTUS's lazy import stubs (a stub the process never
# called is unbound -> dyld binder, LOG 2026-10-08). One archive member per
# shim, so only functions that use a shim are relinked.
