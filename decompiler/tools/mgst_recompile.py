def cname(n):
    s = n.replace("<EXTERNAL>::", "").replace("::", "__")
    s = re.sub(r"[^A-Za-z0-9_]", "_", s)
    return s if s and not s[0].isdigit() else "_" + s


def selrefs():
    """selector name -> address of its __objc_selrefs slot."""
    m = macho.MachO(REF_EXE)
    sec = m.section("__DATA", "__objc_selrefs")
    out = {}
    for i in range(sec[3] // 4):
        slot = sec[2] + 4 * i
        p = struct.unpack_from("<I", m.data, m.off(slot))[0]
        out.setdefault(m.cstr(p), slot)
    return out


def fix_types_header():
    p = os.path.join(CDIR, "mgst_types.gen.h")
    s = open(p).read()
    s = s.replace('#include "ghidra_types.h"', '#include "ghidra_ops.h"')
    s = re.sub(r"^typedef unsigned char\s+bool;\n", "typedef unsigned char _gbool;\n#define bool _gbool\n", s, flags=re.M)
    s = re.sub(r"\bstring\b(?=\s*\*)", "char", s)
    s = re.sub(r"\bpointer\b(?=\s+\w+;)", "void *", s)
    # duplicate member names (Ghidra's objc_property {name, name})
    def dedup(mo):
        body, seen, out = mo.group(2), collections.Counter(), []
        for line in body.split("\n"):
            m2 = re.match(r"^(\s+.*?\b)(\w+)((?:\[[^\]]*\])*;)$", line)
            if m2:
                seen[m2.group(2)] += 1
                if seen[m2.group(2)] > 1:
                    line = "%s%s_%d%s" % (m2.group(1), m2.group(2), seen[m2.group(2)], m2.group(3))
            out.append(line)
        return mo.group(1) + "\n".join(out) + mo.group(3)
    s = re.sub(r"(struct \w+ \{\n)(.*?)(\n\};)", dedup, s, flags=re.S)
    # an empty (opaque) struct is 1 byte in Ghidra's model, 0 in GNU C: pointer
    # arithmetic on it (Ghidra prints byte offsets `p + n*0x18`) would not move
    # (also Ghidra's `{ /* PlaceHolder Structure */` bodies: size 0 in GNU C,
    # so `param_1 + 0x14` on an AudioStreamBasicDescription* moved by 0)
    s = re.sub(r"^(struct \w+ \{)[ \t]*(/\*[^*]*\*/)?[ \t]*\n\};", r"\1 \2 unsigned char __opaque; };", s, flags=re.M)
    open(os.path.join(CDIR, "mgst_types.h.c"), "w")  # placeholder so the dir listing shows provenance
    open(os.path.join(CDIR, "mgst_types.fixed.h"), "w").write(s)
    open(os.path.join(CDIR, "ghidra_ops.h"), "w").write(OPS_H)
    os.remove(os.path.join(CDIR, "mgst_types.h.c"))


def declarator(ctype, name):
    ctype = ctype.strip()
    # Ghidra's string types are variable-length char ARRAYS (the header's
    # `typedef char string` is one char: X + i would add to the value)
    if ctype in ("string", "TerminatedCString", "unicode", "TerminatedUnicode", "char[]"):
        return "char %s[]" % name
    m = re.match(r"^(.*?)\s*((?:\[\d+\])+)$", ctype)
    if m:
        return "%s %s%s" % (m.group(1), name, m.group(2))
    return "%s %s" % (ctype, name)


STACK_APPROX = []
CONV_SITES = []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    a = ap.parse_args()
    os.makedirs(FDIR, exist_ok=True)
    fix_types_header()
    build_vfp_shims()

    funcs = [json.loads(l) for l in open(os.path.join(CDIR, "functions.jsonl"))]
    syms = {}
    for line in open(os.path.join(CDIR, "symbols.tsv")):
        p = line.rstrip("\n").split("\t")
        if p[0] == "name":
            continue
        syms.setdefault(p[1], (int(p[2], 16), p[3], p[4]))
    protos = {}
    for f in funcs:
        protos[f["cname"]] = f
    # dyld-bound externals: read through their binding slot (ExportCompilable
    # extslots.tsv); Ghidra's placeholder address is not the real object
    extslot = {}
    xp = os.path.join(CDIR, "extslots.tsv")
    if os.path.exists(xp):
        for line in open(xp):
            p = line.rstrip("\n").split("\t")
            if p[0] != "cname":
                extslot[p[0]] = int(p[2], 16)
    sels = selrefs()
    sigs = load_signatures()

    ident = re.compile(r"\b[A-Za-z_]\w*\b")
    hdr = open(os.path.join(CDIR, "mgst_types.fixed.h")).read() + OPS_H
    typenames = set(re.findall(r"\btypedef\b[^;]*?\b(\w+)\s*(?:,[^;]*)?;", hdr))
    typenames |= set(re.findall(r"\b(?:struct|union|enum)\s+(\w+)", hdr))
    typenames |= set(re.findall(r"#define\s+(\w+)", hdr))
    typenames |= set(re.findall(r"typedef\s+[^;(]*\(\s*\*?\s*(\w+)\s*\)", hdr))
    for body in re.findall(r"enum\s+\w*\s*\{([^}]*)\}", hdr):
        typenames |= set(re.findall(r"\b([A-Za-z_]\w*)\s*(?:=|,|$)", body))
    # struct typedef names (for `(Struct)(expr)` reinterpretation)
    struct_names = set(re.findall(r"typedef struct \w+ (\w+)\b", hdr))
    KEYWORDS = set("""auto break case char const continue default do double else enum extern float for goto if
        inline int long register restrict return short signed sizeof static struct switch typedef union unsigned
        void volatile while _Bool bool true false this""".split())
    jobs = []
    for f in funcs:
        if f.get("c") is None:
            continue
        if a.only and f["name"] not in a.only and f["addr"] not in a.only and f["cname"] not in a.only:
            continue
        jobs.append(f)

    def build(f):
        src = f["c"]
        # the exporter's leading comment block names the function too - keep it out of the rewrite
        lead = ""
        mlead = re.match(r"^(\s*(?:/\*.*?\*/\s*)+)", src, re.S)
        if mlead:
            lead, src = mlead.group(1), src[mlead.end():]
        ns = f["name"].rsplit("::", 1)[0] if "::" in f["name"] else None
        # 1. qualified names -> C identifiers
        src = src.replace("<EXTERNAL>::", "").replace("__thiscall", "")
        src = re.sub(r"\b((?:\w+::)+\w+)", lambda m: cname(m.group(1)), src)
        # 1a. Ghidra partial access `x._OFF_SIZE_` (SUBPIECE of a scalar or
        #     field) -> that many bytes at that offset of x
        src = re.sub(r"(?<![\w.>])(\w+(?:(?:\.|->)\w+)*)\._(\d+)_(\d+)_\b",
                     lambda m: "(*(%s *)((unsigned char *)&(%s) + %s))" % (
                         _T.get(int(m.group(3)), "unsigned long long"), m.group(1), m.group(2)), src)
        # 1d. 16-byte temporaries `undefined1 auVarN [16]` (Ghidra joins a
        #     by-value struct from registers + stack this way, with shifts)
        #     -> a real 128-bit integer
        src = re.sub(r"\bundefined1\s+(\w+)\s*\[16\]", r"unsigned _BitInt(128) \1", src)
        # 1e. `(StructType)(integer expr)` is no C cast: same-size reinterpretation
        src = cast_struct_bitcast(src, struct_names)
        # 1g. ___fixuns{s,d}fsivfp are modelled in Ghidra as a 64-bit signed
        #     trunc + low word (p-code has no unsigned trunc), printed
        #     `(uint)(longlong)x`. The helper is vcvt.u32 (saturating: <0 -> 0,
        #     >= 2^32 -> 0xffffffff); `(unsigned int)x` compiles to the
        #     __fixuns*fsi shim = that same instruction. All 13 sites are this.
        src = re.sub(r"\((?:uint|ulong|undefined4|dword)\)\(longlong\)", "(unsigned int)", src)
        # 1h. `(ulonglong)(double)x` next to SUB84((double)x,0) is the high word of
        #     the double's BITS (Ghidra's CAST, not a value conversion); only in
        #     Texture2D description's %f arguments
        src = re.sub(r"\((?:ulonglong|longlong|undefined8)\)\(double\)((?:\w|->|\.|\[[^\]]*\])+)",
                     r"__U64((double)\1)", src)
        # 1f. split stack arrays: stack-named locals -> views into one frame
        #     buffer at their original entry-SP offsets (see stack_frame_overlay)
        src, _nframe = stack_frame_overlay(src)
        # 1c. stack0xNN (entry-SP relative address) -> approximation, reported
        src, n_stack = re.subn(r"\bstack0x([0-9a-f]+)\b", r"__ENTRY_STACK(0x\1)", src)
        # 1b. typed objc_msgSend calls (selector still a literal here)
        src, _nt = type_msgsend_calls(src, sigs, f.get("sites"))
        # 1i. stret results the original never reads (analysis/symbols/stret_dead.tsv,
        #     binary-cited): Ghidra merges all versions of an address-tied stack
        #     buffer, so a value saved from the FIRST call prints as the buffer
        #     after a later call overwrote it. Such a later call writes a
        #     throwaway buffer instead (as the original's value flow does).
        # 1j. untyped objc_msgSend sites whose selector is a phi of several
        #     constants (ApplyCallsiteSignatures types one selector per site):
        #     analysis/symbols/msgsend_site_protos.tsv gives the prototype all
        #     of them share word-for-word (floats travel as bits, not promoted)
        for site, ctype in SITE_PROTOS.get(f["addr"], ()):
            src, k = re.subn(r"(/\*@%s\*/)_objc_msgSend\(" % site,
                             lambda m: "%s((%s)_objc_msgSend)(" % (m.group(1), ctype), src, count=1)
            if not k:
                raise SystemExit("msgsend_site_protos.tsv: site %s not found in %s" % (site, f["addr"]))
        for site in STRET_DEAD.get(f["addr"], ()):
            src, k = re.subn(r"(/\*@%s\*/\(\([^;]*?_objc_msgSend_stret\)\()&(\w+)," % site,
                             lambda m: "%s&(__typeof__(%s)){0}," % (m.group(1), m.group(2)), src, count=1)
            if not k:
                raise SystemExit("stret_dead.tsv: site %s not found in %s" % (site, f["addr"]))
        # 2. selectors: ObjC compares SEL by pointer, so use the original selref slot
        def sel(m):
            s = m.group(1)
            return "(*(char **)0x%x)" % sels[s] if s in sels else m.group(0)
        src = re.sub(r'"((?:[^"\\]|\\.)*)"', sel, src)
        # 2b. other string literals: the original string's address
        src = re.sub(r'/\*@s:(0x[0-9a-f]+)\*/"(?:[^"\\]|\\.)*"', r"((char *)\1)", src)
        # 3. unqualified calls to methods of the same C++ class
        if ns:
            pre = cname(ns) + "__"
            src = re.sub(r"\b([A-Za-z_]\w*)(\s*\()", lambda m: pre + m.group(1) + m.group(2)
                         if (pre + m.group(1)) in protos and m.group(1) not in protos and m.group(1) not in typenames
                         else m.group(0), src)
        # 4. the definition gets its own name
        src = re.sub(r"\b%s\s*\(" % re.escape(f["cname"]), "REC_%s(" % f["cname"], src, count=1)
        # 5. declarations for referenced functions / globals
        used = set(ident.findall(src))
        decls = []
        for u in sorted(used):
            if u == "REC_" + f["cname"] or u in typenames or u in KEYWORDS:
                continue
            if u in extslot and u not in protos:
                slot = "DAT_%08x" % extslot[u]
                decls.append("extern char *%s; /* binding slot of %s */" % (slot, u))
                decls.append("#define %s (*%s)" % (u, slot))
                continue
            if u in protos:
                pr = protos[u]["proto"].replace("__thiscall", "").replace("<EXTERNAL>::", "")
                pr = re.sub(r"\b((?:\w+::)+\w+)", lambda m: cname(m.group(1)), pr).strip().rstrip(";")
                # the declared name is the (possibly unique, overload) cname
                base_n = cname(protos[u]["name"])
                if base_n != u:
                    pr = re.sub(r"\b%s(\s*\()" % re.escape(base_n), u + r"\1", pr, count=1)
                decls.append(pr + ";")
            elif u in f.get("globals", {}):
                # exactly the type the decompiler printed this global with here
                decls.append("extern %s;" % declarator(f["globals"][u], u))
            elif re.match(r"^_?(?:[a-z]{0,3}Ram|DAT|LAB|UNK)_?[0-9a-f]{8}$", u):
                # absolute address without a symbol (linked by address, see mgst_difftest.link)
                decls.append("extern %s;" % declarator(f.get("globals", {}).get(u, "undefined4"), u))
            elif u in syms and syms[u][1] == "data":
                ct = syms[u][2]
                if (not ct or ct.startswith("undefined")) and unary_deref(src, u):
                    ct = "int *"          # literal-pool word the code dereferences
                decls.append("extern %s;" % declarator(ct or "undefined4", u))
            elif u in syms:
                decls.append("extern void %s();" % u)
        body = "#include \"mgst_types.fixed.h\"\n" + "\n".join(decls) + "\n\n" + lead + src
        base = os.path.join(FDIR, f["addr"])
        open(base + ".c", "w").write(body)
        body2, nconv = bitcast_implicit_conversions(base + ".c", body)
        if nconv:
            open(base + ".c", "w").write(body2)
            CONV_SITES.append((f["addr"], nconv))
        r = subprocess.run(["clang"] + CFLAGS + ["-I", CDIR, "-c", base + ".c", "-o", base + ".o"],
                           capture_output=True, text=True)
        err = [l for l in r.stderr.splitlines() if " error: " in l]
        if n_stack:
            STACK_APPROX.append((f["addr"], f["name"]))
        return f, r.returncode == 0, err

    ok, bad, cats = 0, 0, collections.Counter()
    fails = []
    with cf.ThreadPoolExecutor(a.jobs) as ex:
        for f, success, err in ex.map(build, jobs):
            if success:
                ok += 1
            else:
                bad += 1
                first = re.sub(r"^.*?error: ", "", err[0]) if err else "?"
                cats[re.sub(r"'[^']*'", "'X'", first)] += 1
                fails.append((f["addr"], f["name"], first))
    lines = ["# Recompile report (step 7')", "", "| | |", "|---|---:|",
             "| functions | %d |" % (ok + bad), "| compiled | **%d** |" % ok, "| failed | %d |" % bad, "",
             "## Failure categories (first error)", ""]
    for k, v in cats.most_common():
        lines.append("- %d x `%s`" % (v, k))
    lines += ["", "## Failures", ""] + ["- %s `%s`: %s" % x for x in sorted(fails)]
    lines += ["", "## Implicit float<->int conversions made bit copies", "",
              "%d function(s), %d site(s): Ghidra's implicit conversions are COPY/STORE of the bits "
              "(real conversions are explicit casts); wrapped in __BITCAST." % (
                  len(CONV_SITES), sum(n for _, n in CONV_SITES)), ""]
    lines += ["- %s (%d)" % x for x in sorted(CONV_SITES)]
    lines += ["", "## Entry-stack approximations (V0 manual audit)", "",
              "Ghidra's `stack0xNN` (an address at entry SP + NN: SjLj exception context, crt0 argv)",
              "has no C equivalent; it is approximated from `__builtin_frame_address(0)`.", ""]
    lines += ["- %s `%s`" % x for x in sorted(STACK_APPROX)]
    open(os.path.join(CDIR, "compile_report.md"), "w").write("\n".join(lines) + "\n")
    print("compiled %d / %d" % (ok, ok + bad))
    for k, v in cats.most_common(15):
        print("  %4d  %s" % (v, k))


if __name__ == "__main__":
    main()
