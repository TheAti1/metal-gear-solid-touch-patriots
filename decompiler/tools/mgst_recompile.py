def load_signatures():
    """selector -> (ret_ctype, [param ctypes], varargs, stret) when the same in
    every class (pointers folded), from analysis/objc/types.spec + external_methods.tsv."""
    spec = os.path.join(ROOT, "analysis/objc/types.spec")
    structs, cur = {}, None
    rows = [l.rstrip("\n").split("\t") for l in open(spec)]
    for p in rows:
        if p[0] == "STRUCT":
            cur = p[1]; structs[cur] = []
        elif p[0] == "FIELD" and cur in structs:
            structs[cur].append(p[3])
        elif p[0] != "FIELD":
            cur = None

    def ctype(t):
        if t in CT:
            return CT[t]
        if t.startswith("ptr(") or t.startswith("arr("):
            return "void *"
        return None

    def flat(t):
        if t.startswith("struct("):
            n = t[7:-1]
            out = []
            for ft in structs.get(n, []):
                out += flat(ft)
            return out
        c = ctype(t)
        return [c] if c else ["int"]

    def ssize(t):
        n = t[7:-1]
        sz = 0
        for ft in structs.get(n, []):
            sz += 8 if ft in ("f8", "i8", "u8") else 2 if ft in ("i2", "u2") else 1 if ft in ("i1", "u1", "bool") else 4
        return sz

    by_sel = collections.defaultdict(set)
    for p in rows:
        if p[0] != "METHOD":
            continue
        ret, args = p[5], p[8:]
        params = []
        for a_ in args:
            params += flat(a_)
        stret = ret.startswith("struct(") and ssize(ret) > 4
        rc = "void" if stret else ("int" if ret.startswith("struct(") else (ctype(ret) or "int"))
        by_sel[p[3]].add((rc, tuple(params), False, stret))
    for l in open(os.path.join(ROOT, "analysis/objc/external_methods.tsv")):
        if l.startswith("#"):
            continue
        p = l.rstrip("\n").split("\t")
        params = []
        for a_ in [x for x in p[2].split(",") if x]:
            params += flat(a_)
        stret = p[1].startswith("struct(") and ssize(p[1]) > 4
        rc = "void" if stret else (ctype(p[1]) or "int")
        by_sel[p[0]].add((rc, tuple(params), p[3] == "1", stret))
    out = {}
    for sel, sigs in by_sel.items():
        if len(sigs) == 1:
            out[sel] = next(iter(sigs))
    return out


def split_call(src, i):
    """src[i] is '(' of a call: return (end_index_after_close, [arg strings])."""
    depth, args, cur, j = 0, [], "", i
    while j < len(src):
        ch = src[j]
        if ch == "(":
            depth += 1
            if depth == 1:
                j += 1
                continue
        elif ch == ")":
            depth -= 1
            if depth == 0:
                args.append(cur)
                return j + 1, args
        elif ch == "," and depth == 1:
            args.append(cur); cur = ""
            j += 1
            continue
        elif ch == '"':
            k = j + 1
            while k < len(src) and src[k] != '"':
                k += 2 if src[k] == "\\" else 1
            cur += src[j:k + 1]; j = k + 1
            continue
        if depth >= 1:
            cur += ch
        j += 1
    return None, None


