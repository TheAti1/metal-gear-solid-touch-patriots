def pool_selector(expr):
    """`(char *)*DAT_0001d8ec` / `*DAT_...`: the literal-pool word holds the
    address of a __objc_selrefs slot -> selector name (static)."""
    global _BIN, _SLOT2SEL
    m = re.search(r"\*\s*_?DAT_([0-9a-f]{8})\b", expr)
    if not m:
        return None
    if _BIN is None:
        _BIN = macho.MachO(REF_EXE)
