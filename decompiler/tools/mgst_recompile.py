def type_msgsend_calls(src, sigs, sites=None):
    """_objc_msgSend[Super2|_stret](recv, "sel", ...) -> call through a pointer of
    the method's real type, so float/double/char/struct returns and float
    arguments use the right registers and conversions (as in the original).
    First choice: the call site's own prototype from Ghidra (ExportCompilable
    marks each call `/*@0xSITE*/` and exports the override under "sites"; it
    knows the receiver class). Fallback: the selector's signature if the same
    in every class."""
    out, pos, n_typed = [], 0, 0
    for m in re.finditer(r"\b(_objc_msgSend(?:Super2|_stret)?)\s*\(", src):
        if m.start() < pos:
            continue
        end, args = split_call(src, m.end() - 1)
        if end is None:
            continue
        mk = re.search(r"/\*@(0x[0-9a-f]+)\*/$", src[:m.start()])
        sp = (sites or {}).get(mk.group(1)) if mk else None
        if sp:
            plist = ", ".join(sp["params"] + (["..."] if sp["varargs"] else []))
            fp = "((%s (*)(%s))%s)" % (sp["ret"], plist or "void", m.group(1))
            out.append(src[pos:m.start()])
            out.append(fp + src[m.end() - 1:end])
            pos = end
            n_typed += 1
            continue
        stret = m.group(1).endswith("_stret")
        k = 2 if stret else 1
        sel = args[k].strip() if len(args) > k else ""
        ms = re.match(r'^"((?:[^"\\]|\\.)*)"$', sel)
        psel = None if ms else pool_selector(sel)
        if ms and ms.group(1) in sigs:
            rc, params, varargs, _st = sigs[ms.group(1)]
        elif psel and psel in sigs:
            rc, params, varargs, _st = sigs[psel]
        else:
            # selector held in a variable (compiler-merged call site): the
            # function assigns its candidates; usable if they share one signature
            mv = re.match(r"^\(?\s*(?:\(char \*\))?\s*(\w+)\s*\)?$", sel)
            if not mv:
                continue
            cands = set(re.findall(r"\b%s\s*=\s*(?:\(char \*\))?\s*\"((?:[^\"\\\\]|\\\\.)*)\"" % re.escape(mv.group(1)), src))
            for rhs in re.findall(r"\b%s\s*=\s*([^;]+);" % re.escape(mv.group(1)), src):
                ps = pool_selector(rhs)
                if ps:
                    cands.add(ps)
            got = {sigs[c] for c in cands if c in sigs}
            if not cands or len(got) != 1 or len(got) != len({1 for c in cands if c in sigs}) and len(cands) != sum(1 for c in cands if c in sigs):
                continue
            rc, params, varargs, _st = next(iter(got))
        head = ["void *", "void *", "char *"] if stret else ["void *", "char *"]
        plist = ", ".join(head + list(params) + (["..."] if varargs else []))
        fp = "((%s (*)(%s))%s)" % ("void" if stret else rc, plist, m.group(1))
        out.append(src[pos:m.start()])
        out.append(fp + src[m.end() - 1:end])
        pos = end
        n_typed += 1
    out.append(src[pos:])
    return "".join(out), n_typed


def cast_struct_bitcast(src, struct_names):
    """`(CGRect)(expr)` -> __BITCAST(CGRect, (expr)) for struct typedef names."""
    out, pos = [], 0
    for m in re.finditer(r"\((\w+)\)\(", src):
        if m.start() < pos or m.group(1) not in struct_names:
            continue
        end, _args = split_call(src, m.end() - 1)
        if end is None:
            continue
        out.append(src[pos:m.start()])
        out.append("__BITCAST(%s, %s)" % (m.group(1), src[m.end() - 1:end]))
        pos = end
    out.append(src[pos:])
    return "".join(out)


def unary_deref(src, name):
    """True if NAME appears as the operand of a unary `*` (not multiplication):
    the previous non-space token is an operator/open bracket, or a cast."""
    for m in re.finditer(r"\*\s*%s\b" % re.escape(name), src):
        before = src[:m.start()].rstrip()
        if not before:
            return True
        c = before[-1]
        if c in "(,=!&|?:;{}+-<>~^%/" or before.endswith("return"):
            return True
        if c == ")" and re.search(r"\([A-Za-z_][\w ]*\**\s*\)$", before):
            return True
    return False


